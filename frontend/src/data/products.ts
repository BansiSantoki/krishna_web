const metalLabels: Record<MetalKey, string> = {
  gold24: '24K Yellow Gold',
  gold22: '22K Yellow Gold',
  gold18: '18K Gold',
  silver: '925 Sterling Silver',
  platinum: '950 Platinum'
};

const purityLabels: Record<MetalKey, string> = {
  gold24: '999 · 24 Karat',
  gold22: '916 BIS Hallmark',
  gold18: '750 BIS Hallmark',
  silver: '925 Sterling',
  platinum: '950 Platinum · PT hallmark'
};

interface Seed {
  name: string;
  category: string;
  subCategory: string;
  metal: MetalKey;
  weight: number;
  stoneValue?: number;
  stoneDetail?: string;
  makingPct?: number;
  discountPct?: number;
  rating: number;
  reviews: number;
  occasion: string[];
  gender?: Gender;
  images: string[];
  tags?: Product['tags'];
  badge?: string;
  rentPerDay?: number;
  inStock?: boolean;
  description: string;
  certificate?: string;
  deliveryDays?: number;
}

const slugify = (value: string) =>
value.
toLowerCase().
replace(/[^a-z0-9]+/g, '-').
replace(/(^-|-$)/g, '');

function build(seed: Seed, index: number): Product {
  return {
    id: `KJ-${String(1001 + index)}`,
    slug: slugify(seed.name),
    name: seed.name,
    category: seed.category,
    subCategory: seed.subCategory,
    images: seed.images,
    metal: seed.metal,
    metalLabel: metalLabels[seed.metal],
    purity: purityLabels[seed.metal],
    weight: seed.weight,
    stoneValue: seed.stoneValue ?? 0,
    stoneDetail: seed.stoneDetail,
    makingPct: seed.makingPct ?? 12,
    discountPct: seed.discountPct ?? 0,
    rating: seed.rating,
    reviews: seed.reviews,
    occasion: seed.occasion,
    gender: seed.gender ?? 'women',
    inStock: seed.inStock ?? true,
    badge: seed.badge,
    tags: seed.tags ?? [],
    rentPerDay: seed.rentPerDay,
    description: seed.description,
    hallmark: seed.metal === 'silver' ? '925 Sterling stamp' : 'BIS Hallmarked · HUID certified',
    certificate: seed.certificate,
    deliveryDays: seed.deliveryDays ?? 5,
    has360: true,
    hasVideo: index % 2 === 0
  };
}

