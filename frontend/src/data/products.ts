export const productBySlug = (slug: string): Product | undefined =>
products.find((product) => product.slug === slug);

export const productById = (id: string): Product | undefined =>
products.find((product) => product.id === id);

export const byTag = (tag: Product['tags'][number], limit?: number): Product[] => {
  const list = products.filter((product) => product.tags.includes(tag));
  return typeof limit === 'number' ? list.slice(0, limit) : list;
};

export const byCategory = (slug: string): Product[] =>
products.filter((product) => product.category === slug);

export const relatedProducts = (product: Product, limit = 4): Product[] =>
products.
filter((item) => item.id !== product.id && (item.category === product.category || item.subCategory === product.subCategory)).
slice(0, limit);